const AIRLINE_BY_CODE = new Map(AIRLINES.map((airline) => [airline.code, airline]));

export function getAirline(code: string): Airline | undefined {
  return AIRLINE_BY_CODE.get(code.toUpperCase());
}

export function requireAirline(code: string): Airline {
  const airline = getAirline(code);
  if (!airline) throw new Error(`Unknown airline ${code}`);
  return airline;
}
